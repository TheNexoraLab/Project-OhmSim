import { prisma } from '@/lib/prisma/client';
import { hashPassword } from '@/lib/auth/password';
import { createAuthClient } from '@neondatabase/auth';
import type { User } from '@prisma/client';

export const DEFAULT_NEON_AUTH_BASE_URL =
  'https://ep-dry-cake-aybu1v2w.neonauth.c-5.us-east-2.aws.neon.tech/neondb/auth';

/**
 * Returns the configured Neon Auth base URL.
 */
export function getNeonAuthBaseUrl(): string {
  return (
    process.env.NEON_AUTH_BASE_URL ||
    process.env.NEXT_PUBLIC_NEON_AUTH_BASE_URL ||
    DEFAULT_NEON_AUTH_BASE_URL
  );
}

/**
 * Determines the application origin URL (e.g., https://ohmsim.ph or http://localhost:3000)
 * based on incoming request headers or environment configuration.
 *
 * NOTE: Neon Auth (Managed Better Auth) enforces a trusted domain allowlist.
 * While `localhost` and its wildcard ports are allowed by default, `127.0.0.1` is rejected
 * with HTTP 403 INVALID_CALLBACKURL. This helper automatically normalizes `127.0.0.1`
 * to `localhost` to guarantee seamless OAuth redirects regardless of whether the user
 * visits via http://localhost:3000 or http://127.0.0.1:3000.
 */
export function getAppOrigin(request?: Request): string {
  if (request) {
    const forwardedHost = request.headers.get('x-forwarded-host');
    let host = forwardedHost || request.headers.get('host');
    if (host) {
      if (host.startsWith('127.0.0.1')) {
        host = host.replace('127.0.0.1', 'localhost');
      }
      const forwardedProto = request.headers.get('x-forwarded-proto');
      const proto =
        forwardedProto || (host.startsWith('localhost') ? 'http' : 'https');
      return `${proto}://${host}`;
    }
  }

  if (process.env.VERCEL_URL) {
    return `https://${process.env.VERCEL_URL}`;
  }

  if (process.env.NEXT_PUBLIC_APP_URL) {
    let appUrl = process.env.NEXT_PUBLIC_APP_URL.replace(/\/$/, '');
    if (appUrl.includes('127.0.0.1')) {
      appUrl = appUrl.replace('127.0.0.1', 'localhost');
    }
    return appUrl;
  }

  return 'http://localhost:3000';
}

/**
 * Signs up a user via Neon's Managed Better Auth SDK.
 */
export async function signUpWithNeonAuth(payload: {
  email: string;
  password: string;
  name: string;
  origin?: string;
}): Promise<{ success: boolean; neonUserId?: string; error?: string }> {
  const baseUrl = getNeonAuthBaseUrl();
  const client = createAuthClient(baseUrl);
  const appOrigin = payload.origin || getAppOrigin();

  try {
    const result = await client.signUp.email(
      {
        email: payload.email,
        password: payload.password,
        name: payload.name,
        callbackURL: appOrigin,
      },
      {
        headers: {
          Origin: appOrigin,
        },
      }
    );

    if (result.error) {
      return {
        success: false,
        error: result.error.message || 'Neon Auth sign-up rejected.',
      };
    }

    return {
      success: true,
      neonUserId: result.data?.user?.id,
    };
  } catch (err: unknown) {
    return {
      success: false,
      error: err instanceof Error ? err.message : 'Failed to connect to Neon Auth service.',
    };
  }
}

export interface SocialInitResult {
  success: boolean;
  url?: string;
  error?: string;
}

/**
 * Calls Neon Auth's /sign-in/social endpoint to initiate Google OAuth.
 * Returns the Google authorization URL generated by Neon Auth.
 */
export async function initiateGoogleSocialLogin(callbackUrl: string): Promise<SocialInitResult> {
  const baseUrl = getNeonAuthBaseUrl();
  try {
    const res = await fetch(`${baseUrl}/sign-in/social`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        provider: 'google',
        callbackURL: callbackUrl,
      }),
    });

    if (!res.ok) {
      const errorText = await res.text();
      return {
        success: false,
        error: `Neon Auth returned HTTP ${res.status}: ${errorText}`,
      };
    }

    const data = await res.json();
    if (!data.url) {
      return {
        success: false,
        error: 'Neon Auth response did not contain an authorization URL.',
      };
    }

    return {
      success: true,
      url: data.url,
    };
  } catch (err: unknown) {
    return {
      success: false,
      error: err instanceof Error ? err.message : 'Failed to reach Neon Auth service.',
    };
  }
}

export interface NeonAuthSessionResult {
  neonUserId: string;
  email: string;
  name: string | null;
  image: string | null;
}

/**
 * Resolves a Neon Auth session by token, querying PostgreSQL neon_auth schema.
 */
export async function resolveNeonSessionByToken(token: string): Promise<NeonAuthSessionResult | null> {
  try {
    const rows = await prisma.$queryRawUnsafe<
      Array<{
        neonUserId: string;
        email: string;
        name: string | null;
        image: string | null;
      }>
    >(
      `SELECT 
         u.id as "neonUserId", 
         u.email, 
         u.name, 
         u.image 
       FROM "neon_auth"."session" s 
       JOIN "neon_auth"."user" u ON s."userId" = u.id 
       WHERE s.token = $1 AND s."expiresAt" > NOW() 
       LIMIT 1;`,
      token
    );

    if (rows && rows.length > 0) {
      return rows[0];
    }
    return null;
  } catch (error) {
    console.warn('Could not resolve neon_auth session via direct DB query:', error);
    return null;
  }
}

/**
 * Fetches the latest active session in neon_auth within the last 5 minutes.
 * Used as a fallback when OAuth callback lacks explicit cookie on the initial redirect.
 */
export async function getLatestNeonSession(): Promise<NeonAuthSessionResult | null> {
  try {
    const rows = await prisma.$queryRawUnsafe<
      Array<{
        neonUserId: string;
        email: string;
        name: string | null;
        image: string | null;
      }>
    >(
      `SELECT 
         u.id as "neonUserId", 
         u.email, 
         u.name, 
         u.image 
       FROM "neon_auth"."session" s 
       JOIN "neon_auth"."user" u ON s."userId" = u.id 
       WHERE s."expiresAt" > NOW() AND s."createdAt" >= (NOW() - INTERVAL '5 minutes')
       ORDER BY s."createdAt" DESC 
       LIMIT 1;`
    );

    if (rows && rows.length > 0) {
      return rows[0];
    }
    return null;
  } catch (error) {
    console.warn('Could not query latest neon_auth session:', error);
    return null;
  }
}

/**
 * Synchronizes an authenticated Google / Neon Auth user into OhmSim's Prisma User model.
 * If user does not exist, an account is created with BUYER role.
 */
export async function syncNeonUserToOhmSim(neonUser: {
  email: string;
  name?: string | null;
}): Promise<User> {
  const cleanEmail = neonUser.email.toLowerCase().trim();

  let user = await prisma.user.findUnique({
    where: { email: cleanEmail },
  });

  if (!user) {
    const rawName = (neonUser.name || 'Google User').trim();
    const parts = rawName.split(/\s+/);
    const firstName = parts[0] || 'Google';
    const lastName = parts.slice(1).join(' ') || 'User';

    // Generate secure random fallback password hash
    const placeholderPassword = `${crypto.randomUUID()}!Aa9`;
    const passwordHash = await hashPassword(placeholderPassword);

    user = await prisma.user.create({
      data: {
        email: cleanEmail,
        firstName,
        lastName,
        passwordHash,
        role: 'BUYER',
      },
    });
  }

  return user;
}
